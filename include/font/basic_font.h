inline const uint8_t *font12cnEnglish(char character) {
    switch (character) {
    case 'A': return FONT12CN_A;
    case 'S': return FONT12CN_S;
    case 'U': return FONT12CN_U;
    case 'N': return FONT12CN_N;
    case 'D': return FONT12CN_D;
    case 'R': return FONT12CN_R;
    default: return nullptr;
    }
}

struct ChineseGlyph {
    uint32_t codepoint;
    uint8_t width;
    uint8_t height;
    const uint8_t *bitmap;
};

// Selected 16 x 21 glyphs copied from reference11/.../Fonts/font12CN.c.
// Each glyph is 42 bytes (16 pixels x 21 rows / 8), stored in flash.
